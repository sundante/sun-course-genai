#!/usr/bin/env node
// Builds the A-Z section of the course glossary (src/content/22-Review/02-Glossary.mdx)
// from the "Key Acronyms, Concepts & Jargon" tables in every module's APPENDIX.mdx.
//   node scripts/build-glossary.mjs          rewrite the region between the glossary markers
//   node scripts/build-glossary.mjs --check  exit non-zero if that region is stale
// The curated section above the start marker is hand-written and never touched.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const ROOT = process.cwd();
const CONTENT = path.join(ROOT, "src/content");
const GLOSSARY = path.join(CONTENT, "22-Review/02-Glossary.mdx");
const START = "<!-- glossary:start - generated by `npm run build:glossary`, do not edit by hand -->";
const END = "<!-- glossary:end -->";
// Same shape isStubFile() in src/lib/content/nav.ts counts as a glossary definition
const ROW = /^\|\s*\*\*([^|]+)\*\*\s*\|\s*([^|]+)\|$/;

// Modules in nav order: title plus the folder of their Summary & Key Terms page
function modulesInNavOrder() {
  const nav = yaml.load(fs.readFileSync(path.join(CONTENT, "nav.yml"), "utf-8")).nav;
  const modules = [];
  const findAppendix = (entries) => {
    for (const entry of entries) {
      if (typeof entry === "string") continue;
      for (const value of Object.values(entry)) {
        if (typeof value === "string" && value.endsWith("/APPENDIX.mdx")) return value;
        if (Array.isArray(value)) {
          const found = findAppendix(value);
          if (found) return found;
        }
      }
    }
    return null;
  };
  for (const entry of nav) {
    if (typeof entry === "string" || "track" in entry) continue;
    for (const [title, value] of Object.entries(entry)) {
      if (!Array.isArray(value)) continue;
      const appendix = findAppendix(value);
      if (appendix) modules.push({ title, appendix, number: String(modules.length + 1).padStart(2, "0") });
    }
  }
  return modules;
}

export function buildGlossarySection() {
  const terms = new Map();
  for (const mod of modulesInNavOrder()) {
    for (const line of fs.readFileSync(path.join(CONTENT, mod.appendix), "utf-8").split("\n")) {
      const m = line.trim().match(ROW);
      if (!m) continue;
      const term = m[1].trim();
      const meaning = m[2].trim();
      const key = term.toLowerCase();
      if (!terms.has(key)) terms.set(key, { term, meaning, modules: [] });
      const entry = terms.get(key);
      if (!entry.modules.includes(mod)) entry.modules.push(mod);
    }
  }

  const sorted = [...terms.values()].sort((a, b) =>
    a.term.localeCompare(b.term, "en", { sensitivity: "base", numeric: true })
  );
  const groups = new Map();
  for (const t of sorted) {
    const first = t.term[0].toUpperCase();
    const letter = /[A-Z]/.test(first) ? first : "0-9";
    if (!groups.has(letter)) groups.set(letter, []);
    groups.get(letter).push(t);
  }

  const out = [
    START,
    "",
    `${sorted.length} terms from the Summary & Key Terms page of every module. Where a term appears in more than one module, the meaning shown is from the first module that defines it.`,
    "",
  ];
  for (const [letter, list] of groups) {
    out.push(`### ${letter}`, "", "| Term | Meaning | Module |", "|---|---|---|");
    for (const t of list) {
      const mods = t.modules
        .map((m) => `[${m.number} ${m.title}](../${m.appendix})`)
        .join(", ");
      out.push(`| **${t.term}** | ${t.meaning} | ${mods} |`);
    }
    out.push("");
  }
  out.push(END);
  return { text: out.join("\n"), count: sorted.length };
}

function splice(current, section) {
  const s = current.indexOf(START.slice(0, 22));
  const e = current.indexOf(END);
  if (s === -1 || e === -1) throw new Error(`${path.relative(ROOT, GLOSSARY)} is missing the glossary markers`);
  return current.slice(0, s) + section + current.slice(e + END.length);
}

export function glossaryIsStale() {
  const current = fs.readFileSync(GLOSSARY, "utf-8");
  return splice(current, buildGlossarySection().text) !== current;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (glossaryIsStale()) {
      console.error("Glossary is stale - run `npm run build:glossary`");
      process.exit(1);
    }
    console.log("Glossary is up to date");
  } else {
    const { text, count } = buildGlossarySection();
    fs.writeFileSync(GLOSSARY, splice(fs.readFileSync(GLOSSARY, "utf-8"), text));
    console.log(`Wrote ${count} terms to ${path.relative(ROOT, GLOSSARY)}`);
  }
}
